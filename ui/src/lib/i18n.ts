const tables: Record<UiLang, Record<Key, string>> = { vi, en };

export function translate(lang: UiLang, key: Key, vars: Record<string, string | number> = {}): string {
  return tables[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function hasKey(key: string): key is Key {
  return key in vi;
}

export function systemLang(languages: readonly string[]): UiLang {
  return languages.some((l) => l.toLowerCase().startsWith("vi")) ? "vi" : "en";
}
